import { desc, eq } from "drizzle-orm";
import { getDb } from "@/lib/db";
import { aiEmployees, meetings, reports } from "@/lib/db/schema";
import { requireUser } from "@/lib/auth/session";
import { Badge, Card, Empty, fmtDateTime, humanize, PageHeader } from "@/components/ui";

export default async function ReportsPage() {
  await requireUser();
  const db = getDb();
  const rows = await db.select({ r: reports, author: aiEmployees.name }).from(reports).leftJoin(aiEmployees, eq(aiEmployees.id, reports.authorEmployeeId)).orderBy(desc(reports.createdAt)).limit(60);
  const mtgs = await db.select().from(meetings).orderBy(desc(meetings.scheduledFor)).limit(20);
  return (
    <div className="space-y-6">
      <PageHeader title="Reports & meetings" subtitle="Generated by AI employees from live data. Each report records whether its figures are actual or estimated." />
      <Card title="Meetings">
        {mtgs.length === 0 ? <Empty title="No meetings held yet">Weekly executive and sales reviews run on Mondays (configurable in Settings).</Empty> : (
          <ul className="space-y-3 text-sm">{mtgs.map((m) => <li key={m.id}><div className="font-medium">{m.title} <Badge>{humanize(m.kind)}</Badge></div><div className="text-xs text-muted">{fmtDateTime(m.startedAt)} · {m.attendeeEmployeeIds.length} attendees · agenda: {m.agenda.join(", ")}</div>{m.minutes && <pre className="mt-1 whitespace-pre-wrap font-sans text-xs">{m.minutes}</pre>}</li>)}</ul>
        )}
      </Card>
      <Card title="Reports">
        {rows.length === 0 ? <Empty title="No reports yet" /> : (
          <ul className="space-y-2">
            {rows.map(({ r, author }) => (
              <li key={r.id}>
                <details className="rounded-md border border-border p-3">
                  <summary className="cursor-pointer text-sm"><span className="font-medium">{r.title}</span> <Badge>{humanize(r.kind)}</Badge> <span className="text-xs text-muted">{author} · {fmtDateTime(r.createdAt)}</span></summary>
                  <pre className="mt-2 max-h-96 overflow-auto rounded bg-surface-2 p-2 text-xs">{JSON.stringify(r.data, null, 2)}</pre>
                </details>
              </li>
            ))}
          </ul>
        )}
      </Card>
    </div>
  );
}
